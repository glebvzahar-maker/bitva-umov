#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Фаза 1 (финал) — полировка:
  • устранение дубля «Лыжная стрелка» (Р1 ↔ Р2);
  • устранение дублирующегося предложения;
  • анти-утечка: выравнивание длин вариантов в трёх вопросах;
  • замена вопроса Р3_4_5 на равнозначный по смыслу.

Запуск:  python3 build/patch_polish.py
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "quiz_data.json")


def main():
    data = json.load(open(DATA, encoding="utf-8"))
    idx = {q["id"]: q for r in data["rounds"] for q in r["questions"]}
    log = []

    # ── 1. Дубль «Лыжная стрелка»: Р1_4_2 → новый вопрос ─────────────────
    q = idx["R1_4_2"]
    q["question"] = ("Сколько тоннелей и мостов оцифровано РЖД с помощью цифровых "
                     "моделей и беспилотных систем?")
    q["options"] = ["162 тоннеля и 22 моста", "86 тоннелей и 14 мостов",
                    "240 тоннелей и 31 мост", "45 тоннелей и 9 мостов"]
    q["answer"] = "А"
    q["explanation"] = (
        "РЖД переводит обследование железнодорожной инфраструктуры в цифровой формат: "
        "оцифрованы 162 тоннеля и 22 моста. Цифровые модели строятся по данным "
        "лазерного сканирования и съёмки с беспилотных летательных аппаратов, поэтому "
        "обследование объекта занимает в три раза меньше времени, чем при传统 "
        "выезде специалистов на место с оборудованием. Цифровой двойник сооружения "
        "позволяет заранее просчитать его состояние, смоделировать нагрузку и "
        "запланировать ремонт до того, как появятся признаки повреждений. "
        "Подход особенно важен для тоннелей и мостов, где очное обследование "
        "требует специальных мер безопасности.")
    log.append("R1_4_2: дубль «Лыжная стрелка» → «162 тоннеля и 22 моста»")

    # ── 2. Дублирующееся предложение в Р1_3_1 ─────────────────────────────
    q = idx["R1_3_1"]
    dup = ("Ответственность машинистов растёт вместе с объёмами перевозок "
           "и скоростью поездов.")
    if q["explanation"].count(dup) > 1:
        first = q["explanation"].find(dup)
        q["explanation"] = (q["explanation"][:first] + dup
                            + q["explanation"][first + len(dup):].replace(dup, "", 1))
        log.append("R1_3_1: убрано дублирующееся предложение")

    # ── 3. Анти-утечка: выравнивание длин вариантов ───────────────────────
    # R2_2_4 «Специальный представитель РЖД» был длиннее остальных
    q = idx["R2_2_4"]
    q["options"][2] = "Начальник железнодорожной станции"
    q["options"][3] = "Слесарь по ремонту подвижного состава"
    log.append("R2_2_4: выровнены длины вариантов")

    # R2_3_5 «Сортировочная горка» была длиннее остальных
    q = idx["R2_3_5"]
    q["options"][0] = "Грузовой вагон"
    q["options"][1] = "Пассажирская платформа"
    q["options"][2] = "Подъездной путь станции"
    log.append("R2_3_5: выровнены длины вариантов")

    # R3_4_5 «Лосиноостровская» была длиннее остальных → равнозначная замена
    q = idx["R3_4_5"]
    q["question"] = ("Какое сооружение защищает горный железнодорожный путь "
                     "от камнепадов и селевых потоков?")
    q["options"] = ["Галерея", "Виадук", "Эстакада", "Путепровод"]
    q["answer"] = "А"
    q["explanation"] = (
        "Галерея - искусственное сооружение, которое устраивают в горном склоне "
        "для защиты железнодорожного пути от осыпей, камнепадов и селевых потоков. "
        "Она принимает на себя удар селевого потока и служит надёжным укрытием "
        "для полотна. Рядом с ней нередко сооружают подпорные стенки и "
        "водопропускные трубы, отводящие воду. Выбор между галереей, тоннелем, "
        " viadуком, эстакадой и путепроводом определяется геологией склона и "
        "экономикой проекта: в горах тоннель или галерея часто дешевле глубокой "
        "выемки и длинного обходного пути. Цифровые модели РЖД позволяют "
        "заранее оценить риск для каждого сооружения.")
    log.append("R3_4_5: «Лосиноостровская» → «Галерея» (анти-утечка + слайд 12)")

    # ── 4. Санитарная проверка текстов ────────────────────────────────────
    for rnd in data["rounds"]:
        for q in rnd["questions"]:
            q["explanation"] = re.sub(r"\s{2,}", " ", q["explanation"]).strip()
            q["explanation"] = q["explanation"].replace("传统 ", "")
            q["explanation"] = q["explanation"].replace("viadуком", "виадуком")
            if q["explanation"] and q["explanation"][-1] not in ".!?":
                q["explanation"] += "."

    json.dump(data, open(DATA, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    for line in log:
        print("  ✓", line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
