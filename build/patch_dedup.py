def main():
    data = json.load(open(DATA, encoding="utf-8"))
    idx = {q["id"]: q for r in data["rounds"] for q in r["questions"]}
    ok, bad = 0, []

    for qid, old, new in REPL:
        q = idx.get(qid)
        if q is None:
            bad.append((qid, "вопрос не найден"))
            continue
        if old not in q["explanation"]:
            bad.append((qid, "фрагмент не найден"))
            continue
        q["explanation"] = q["explanation"].replace(old, new, 1)
        ok += 1

    json.dump(data, open(DATA, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"Замен выполнено: {ok} из {len(REPL)}")
    for qid, why in bad:
        print(f"  ✗ {qid}: {why}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
