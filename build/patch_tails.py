def main():
    data = json.load(open(DATA, encoding="utf-8"))
    applied, missed = 0, []

    for rnd in data["rounds"]:
        for q in rnd["questions"]:
            expl = q["explanation"]
            for old, new in REPLACEMENTS:
                if old in expl:
                    if new:
                        expl = expl.replace(old, new)
                        applied += 1
                    else:
                        # удаляем предложение целиком, вместе с пробелом перед ним
                        expl = re.sub(r"\s*" + re.escape(old), "", expl, count=1)
                        applied += 1
            # чистим возможные «висячие» пробелы и пустые хвосты
            expl = re.sub(r"\s+([.,])", r"\1", expl)
            expl = re.sub(r"\s{2,}", " ", expl).strip()
            if expl and expl[-1] not in ".!?":
                expl += "."
            q["explanation"] = expl

    json.dump(data, open(DATA, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"Хвостов вычищено: {applied}")

    # контроль: сколько фактов осталось
    from collections import Counter
    cnt = Counter()
    FACT = re.compile(r"(1 311,1 млн|3 075,3 млрд|1 115,8 млн|13 152 локомотив|"
                      r"0,397|494,5|93,5 млн|126,7 млн|88 800|253,7 млрд|"
                      r"399 новых|796 300|85 500 км)")
    for rnd in data["rounds"]:
        for q in rnd["questions"]:
            for m in FACT.findall(q["explanation"]):
                cnt[m] += 1
    print("Остаточные цифры отчёта:")
    for k, v in cnt.most_common():
        print(f"   {k:22} {v}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
