# пояснения, где ответ формулируется иначе, чем в варианте
EXPL_FIX = {
    "R1_1_3": [("Жёлтый и белый", "Жёлтый с белым")],
    "R2_3_2": [("«Бегун» - вагон, скатывающийся с сортировочной горки под действием силы тяжести.",
                "«Бегун» - грузовой вагон, скатывающийся с сортировочной горки "
                "под действием силы тяжести.")],
}


def main():
    data = json.load(open(DATA, encoding="utf-8"))
    idx = {q["id"]: q for r in data["rounds"] for q in r["questions"]}
    log = []

    for qid, opts in NEW_OPTIONS.items():
        q = idx.get(qid)
        if q is None:
            print(f"  ✗ {qid}: вопрос не найден")
            continue
        if len(opts) != 4:
            print(f"  ✗ {qid}: должно быть 4 варианта")
            continue
        q["options"] = list(opts)
        log.append(f"{qid}: варианты выровнены → {opts}")

    for qid, pairs in EXPL_FIX.items():
        q = idx.get(qid)
        if not q:
            continue
        for old, new in pairs:
            if old in q["explanation"]:
                q["explanation"] = q["explanation"].replace(old, new)
                log.append(f"{qid}: пояснение уточнено («{old}» → «{new}»)")

    json.dump(data, open(DATA, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    for line in log:
        print("  ✓", line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
