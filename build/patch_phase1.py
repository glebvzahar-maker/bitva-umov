    if q["options"][ai] == "Лосиноостровская":
        q["options"][ai] = "Лосиноостровск."
        applied.append(("R3_4_5: укоротить «Лосиноостровская»", ""))

    # ═══════════════ 15. ПЕРЕСБОРКА СЕТКИ ═══════════════
    new_rounds = []
    for spec in LAYOUT:
        r = {"name": spec["name"], "categories": spec["categories"], "questions": []}
        for cat_row in spec["grid"]:
            for source_id in cat_row:
                if source_id not in idx:
                    missed.append((f"сетка: {source_id}", "вопрос не найден"))
                    continue
                q = dict(idx[source_id])
                q["points"] = (len(r["questions"]) % 5 + 1) * 100
                r["questions"].append(q)
        # проверка: все исходные вопросы раунда использованы ровно один раз
        new_rounds.append(r)

    # раунды сопоставляются по номеру: LAYOUT[0] ↔ исходный раунд 1
    for i, r in enumerate(new_rounds):
        used = {q["id"] for q in r["questions"]}
        expected = {q["id"] for q in rounds[i]["questions"]}
        if used != expected:
            only_new = used - expected
            only_old = expected - used
            missed.append((f"раунд {i + 1}: сетка не совпадает",
                           f"лишние {sorted(only_new)}, потеряны {sorted(only_old)}"))

    # ═══════════════ 16. РЕГЕНЕРАЦИЯ ID И НОМИНАЛОВ ═══════════════
    for ri, r in enumerate(new_rounds, 1):
        for qi, q in enumerate(r["questions"]):
            q["id"] = f"R{ri}_{qi // 5 + 1}_{qi % 5 + 1}"
            q["points"] = (qi % 5 + 1) * 100

    data["rounds"] = new_rounds
    json.dump(data, open(DATA, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    print(f"Применено правок: {len(applied)}")
    for note, why in applied:
        print(f"  ✓ {note}" + (f"  {why}" if why else ""))
    if missed:
        print(f"\nПРОПУЩЕНО ({len(missed)}):")
        for note, why in missed:
            print(f"  ✗ {note}: {why}")
        return 1
    return 0


